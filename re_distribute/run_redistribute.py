from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path

from re_distribute.bam_redistributor import (
    BamRedistributionResult,
    redistribute_and_merge_bams,
)
from re_distribute.em_redistributor import (
    AssignmentWriteResult,
    EmResult,
    run_em,
    write_final_assignments,
)
from re_distribute.gene_groups import (
    build_gene_groups,
    gene_groups_to_dataframe,
)
from re_distribute.initial_tpm import (
    InitialTpmResult,
    calculate_initial_tpm,
)


@dataclass(frozen=True)
class RedistributionResult:
    """Paths and summaries generated by the complete redistribution run."""

    gene_groups_parquet: str
    initial_tpm_parquet: str
    final_tpm_parquet: str
    em_history_tsv: str
    assignments_parquet: str
    redistributed_multi_bam: str
    final_bam: str
    initial_tpm_result: InitialTpmResult
    em_result: EmResult
    assignment_result: AssignmentWriteResult
    bam_result: BamRedistributionResult


def _create_logger(log_file: str) -> logging.Logger:
    logger = logging.getLogger("RiboTxAlignRedistribute")
    logger.setLevel(logging.INFO)
    logger.propagate = False

    for handler in logger.handlers[:]:
        logger.removeHandler(handler)
        handler.close()

    formatter = logging.Formatter(
        "%(asctime)s\t%(levelname)s\t%(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )

    file_handler = logging.FileHandler(
        log_file,
        mode="w",
        encoding="utf-8",
    )
    file_handler.setFormatter(formatter)

    stream_handler = logging.StreamHandler()
    stream_handler.setFormatter(formatter)

    logger.addHandler(file_handler)
    logger.addHandler(stream_handler)

    return logger


def run_redistribution(
    coordinate_tsv: str,
    unique_bam: str,
    multiplemap_bam: str,
    mapping_parquet: str,
    mappability_parquet: str,
    output_prefix: str,
    pseudocount: float = 0.01,
    maximum_iterations: int = 100,
    convergence_threshold: float = 1e-7,
    maximum_allocation_error: float = 0.10,
    random_seed: int = 13,
    sort_threads: int = 8,
    bam_progress_interval: int = 1_000_000,
    parquet_batch_size: int = 100_000,
    log_file: str | None = None,
) -> RedistributionResult:
    """
    Run initial TPM estimation, EM redistribution and final BAM construction.

    Alignment scores are not used in any EM step. Unique reads define the
    initial TPM using the unique-only effective length. Every EM iteration
    adds expected multiple-hit counts to the fixed unique counts and uses the
    non-duplicated one-to-six-hit effective length before TPM renewal.
    After convergence, reads with the same sequence and candidate set are
    allocated in integer counts according to the final candidate posterior.
    Groups exceeding the permitted allocation error remain unresolved.
    """

    prefix_path = Path(output_prefix)
    prefix_path.parent.mkdir(parents=True, exist_ok=True)

    if log_file is None:
        log_file = f"{output_prefix}.redistribute.log"

    logger = _create_logger(log_file)

    gene_groups_parquet = f"{output_prefix}.gene_groups.parquet"
    initial_tpm_parquet = f"{output_prefix}.initial_tpm.parquet"
    final_tpm_parquet = f"{output_prefix}.final_tpm.parquet"
    em_history_tsv = f"{output_prefix}.em_history.tsv"
    assignments_parquet = f"{output_prefix}.em_assignments.parquet"
    redistributed_multi_bam = (
        f"{output_prefix}.redistributed_multi.bam"
    )
    final_bam = f"{output_prefix}.final.bam"

    logger.info("Redistribution started")
    logger.info("Coordinate TSV: %s", coordinate_tsv)
    logger.info("Unique BAM: %s", unique_bam)
    logger.info("Multiple-map BAM: %s", multiplemap_bam)
    logger.info("Mapping Parquet: %s", mapping_parquet)
    logger.info("Mappability Parquet: %s", mappability_parquet)
    logger.info(
        "Maximum sequence allocation error: %.4f",
        maximum_allocation_error,
    )

    group_index = build_gene_groups(coordinate_tsv)
    gene_groups_df = gene_groups_to_dataframe(group_index)
    gene_groups_df.to_parquet(
        gene_groups_parquet,
        index=False,
    )
    logger.info(
        "Gene groups: %d output=%s",
        len(group_index.groups),
        gene_groups_parquet,
    )

    initial_result = calculate_initial_tpm(
        unique_bam=unique_bam,
        mappability_parquet=mappability_parquet,
        group_index=group_index,
        pseudocount=pseudocount,
        progress_interval=bam_progress_interval,
        logger=logger,
    )
    initial_result.table.to_parquet(
        initial_tpm_parquet,
        index=False,
    )
    logger.info(
        "Initial TPM: assigned_unique=%d unassigned_unique=%d output=%s",
        initial_result.unique_read_counts.assigned_records,
        initial_result.unique_read_counts.unassigned_records,
        initial_tpm_parquet,
    )

    em_result = run_em(
        initial_tpm_table=initial_result.table,
        mapping_parquet=mapping_parquet,
        group_index=group_index,
        pseudocount=pseudocount,
        maximum_iterations=maximum_iterations,
        convergence_threshold=convergence_threshold,
        parquet_batch_size=parquet_batch_size,
        logger=logger,
    )
    em_result.final_tpm_table.to_parquet(
        final_tpm_parquet,
        index=False,
    )
    em_result.history_table.to_csv(
        em_history_tsv,
        sep="\t",
        index=False,
    )

    assignment_result = write_final_assignments(
        mapping_parquet=mapping_parquet,
        multiplemap_bam=multiplemap_bam,
        final_tpm_table=em_result.final_tpm_table,
        group_index=group_index,
        output_parquet=assignments_parquet,
        maximum_allocation_error=maximum_allocation_error,
        random_seed=random_seed,
        batch_size=parquet_batch_size,
        logger=logger,
    )

    bam_result = redistribute_and_merge_bams(
        unique_bam=unique_bam,
        multiplemap_bam=multiplemap_bam,
        assignments_parquet=assignments_parquet,
        redistributed_multi_bam=redistributed_multi_bam,
        final_bam=final_bam,
        sort_threads=sort_threads,
        logger=logger,
    )

    logger.info("Redistribution completed")

    return RedistributionResult(
        gene_groups_parquet=gene_groups_parquet,
        initial_tpm_parquet=initial_tpm_parquet,
        final_tpm_parquet=final_tpm_parquet,
        em_history_tsv=em_history_tsv,
        assignments_parquet=assignments_parquet,
        redistributed_multi_bam=redistributed_multi_bam,
        final_bam=final_bam,
        initial_tpm_result=initial_result,
        em_result=em_result,
        assignment_result=assignment_result,
        bam_result=bam_result,
    )
