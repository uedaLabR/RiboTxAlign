def read_truth(path):

    records = []

    tid = None
    plen = None

    with open(path) as f:

        for line in f:

            line = line.strip()

            if line.startswith("tid:"):

                tid = norm_id(
                    line.split(
                        ":",
                        1,
                    )[1]
                )

            elif line.startswith("plen:"):

                plen = int(
                    line.split(
                        ":",
                        1,
                    )[1]
                )

            elif line.startswith("rprofile:"):

                counts = [
                    int(x)
                    for x in (
                        line.split(
                            ":",
                            1,
                        )[1]
                        .split()
                    )
                ]

                records.append({
                    "transcript_id":
                        tid,

                    "truth_length":
                        plen,

                    "truth_count":
                        sum(counts),
                })

    df = (
        pd.DataFrame(
            records
        )
        .groupby(
            "transcript_id",
            as_index=False,
        )
        .agg(
            truth_length=(
                "truth_length",
                "max",
            ),
            truth_count=(
                "truth_count",
                "sum",
            ),
        )
    )

    rate = np.where(
        df["truth_length"] > 0,
        (
            df["truth_count"]
            /
            df["truth_length"]
        ),
        0.0,
    )

    total = rate.sum()

    df["Truth_tpm"] = (
        rate
        /
        total
        *
        1_000_000
        if total > 0
        else 0.0
    )

    return df


