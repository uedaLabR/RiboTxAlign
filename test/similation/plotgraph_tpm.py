def norm_id(x):

    if x is None or pd.isna(x):
        return None

    x = str(x).strip()

    if not x:
        return None

    x = re.sub(
        r"^(transcript:|gene:|rna:)",
        "",
        x,
    )

    return x.split(".")[0]


def safe_name(text):

    return re.sub(
        r"[^A-Za-z0-9_.-]+",
        "_",
        str(text),
    )


def calc_corr(
    truth,
    pred,
):

    truth = np.asarray(
        truth,
        dtype=float,
    )

    pred = np.asarray(
        pred,
        dtype=float,
    )

    if len(truth) < 2:

        return (
            np.nan,
            np.nan,
        )

    pearson = pearsonr(
        truth,
        pred,
    ).statistic

    spearman = spearmanr(
        truth,
        pred,
    ).statistic

    return (
        pearson,
        spearman,
    )


