def read_deepshape(path):

    records = []

    with open(path) as f:

        for line in f:

            line = line.strip()

            if (
                not line
                or
                line.startswith(
                    "Loop "
                )
            ):
                continue

            fields = line.split(
                "\t"
            )

            if len(fields) < 3:
                continue

            try:

                tpm = float(
                    fields[1]
                )

            except ValueError:

                continue

            tid = norm_id(
                fields[0]
            )

            if tid is None:
                continue

            records.append({
                "transcript_id":
                    tid,

                "DeepShape_tpm":
                    tpm,
            })

    return (
        pd.DataFrame(
            records
        )
        .groupby(
            "transcript_id",
            as_index=False,
        )["DeepShape_tpm"]
        .sum()
    )


