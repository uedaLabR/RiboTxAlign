def correlation_plot(
    pairwise,
    method,
    set_type,
):

    method_col = (
        f"{method}_tpm"
    )

    if set_type == "AND":

        tmp = pairwise[
            pairwise[
                "in_truth"
            ]
            &
            pairwise[
                "in_method"
            ]
        ].copy()

        subtitle = (
            "AND: Truth > 0 and Method > 0"
        )

    elif set_type == "OR":

        tmp = pairwise[
            pairwise[
                "in_truth"
            ]
            |
            pairwise[
                "in_method"
            ]
        ].copy()

        subtitle = (
            "OR: Truth > 0 or Method > 0; "
            "missing side = 0"
        )

    else:

        raise ValueError(
            set_type
        )

    truth = (
        tmp[
            "Truth_tpm"
        ]
        .to_numpy(
            float
        )
    )

    pred = (
        tmp[
            method_col
        ]
        .to_numpy(
            float
        )
    )

    (
        pearson,
        spearman,
    ) = calc_corr(
        truth,
        pred,
    )

    x = np.log10(
        truth + 1
    )

    y = np.log10(
        pred + 1
    )

    fig = plt.figure(
        figsize=(
            6,
            6,
        )
    )

    merge_status_col = f"{method}_merge_status"

    if merge_status_col in tmp.columns:

        status = (
            tmp[merge_status_col]
            .fillna("never_merged")
            .astype(str)
            .to_numpy()
        )

        plotting_groups = [
            (
                "never_merged",
                "Never merged",
                5,
                0.35,
                None,
            ),
            (
                "reference_merge",
                "Reference-merged",
                12,
                0.70,
                "orange",
            ),
            (
                "em_merge",
                "EM-merged",
                12,
                0.70,
                "red",
            ),
            (
                "reference_and_em_merge",
                "Reference + EM merged",
                16,
                0.80,
                "purple",
            ),
        ]

        for key, label, size, alpha, color in plotting_groups:
            mask = status == key
            n = int(mask.sum())

            if n == 0:
                continue

            kwargs = {
                "s": size,
                "alpha": alpha,
                "label": f"{label} (n={n:,})",
            }

            if color is not None:
                kwargs["color"] = color

            plt.scatter(
                x[mask],
                y[mask],
                **kwargs,
            )

        plt.legend(
            loc="lower right",
            frameon=False,
        )

    else:

        plt.scatter(
            x,
            y,
            s=5,
            alpha=0.4,
        )

    max_value = max(
        x.max()
        if len(x)
        else 0,
        y.max()
        if len(y)
        else 0,
    )

    plt.plot(
        [
            0,
            max_value,
        ],
        [
            0,
            max_value,
        ],
        linewidth=1,
    )

    plt.xlabel(
        "log10(Simulated transcript TPM + 1)"
    )

    plt.ylabel(
        f"log10({method} transcript TPM + 1)"
    )

    plt.title(
        f"{method} - {set_type}\n"
        f"{subtitle}"
    )

    plt.text(
        0.05,
        0.95,
        (
            f"n = {len(tmp):,} transcripts\n"
            f"Pearson r = {pearson:.3f}\n"
            f"Spearman rho = {spearman:.3f}"
        ),
        transform=(
            plt.gca()
            .transAxes
        ),
        va="top",
    )

    plt.tight_layout()

    path = (
        PLOTS
        / (
            f"{safe_name(method)}"
            f"_{set_type}_correlation.png"
        )
    )

    plt.savefig(
        path,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(
        fig
    )

    return {
        "method":
            method,

        "set":
            set_type,

        "transcripts":
            len(tmp),

        "pearson":
            pearson,

        "spearman":
            spearman,

        "plot_path":
            str(path),
    }


