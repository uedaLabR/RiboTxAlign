def make_pairwise_table(
    truth,
    method_df,
    method_name,
):

    method_col = (
        f"{method_name}_tpm"
    )

    truth_positive = (
        truth[
            truth[
                "Truth_tpm"
            ] > 0
        ][
            [
                "transcript_id",
                "Truth_tpm",
            ]
        ]
    )

    if (
        method_name == "RiboMap"
        and
        "RiboMap_reported"
        in method_df.columns
    ):

        method_positive = (
            method_df[
                method_df[
                    "RiboMap_reported"
                ]
            ][
                [
                    "transcript_id",
                    method_col,
                ]
            ]
        )

    else:

        keep_cols = [
            "transcript_id",
            method_col,
        ]

        optional_cols = [
            f"{method_name}_match_type",
            f"{method_name}_reference_merged",
            f"{method_name}_reference_merge_size",
            f"{method_name}_em_merged",
            f"{method_name}_merge_status",
        ]

        for col in optional_cols:
            if col in method_df.columns:
                keep_cols.append(col)

        method_positive = (
            method_df[
                method_df[
                    method_col
                ] > 0
            ][
                keep_cols
            ]
        )

    truth_set = set(
        truth_positive[
            "transcript_id"
        ]
    )

    method_set = set(
        method_positive[
            "transcript_id"
        ]
    )

    union_ids = (
        truth_set
        |
        method_set
    )

    pairwise = pd.DataFrame({
        "transcript_id":
            sorted(
                union_ids
            )
    })

    pairwise = (
        pairwise
        .merge(
            truth_positive,
            on="transcript_id",
            how="left",
        )
        .merge(
            method_positive,
            on="transcript_id",
            how="left",
        )
    )

    pairwise[
        "Truth_tpm"
    ] = (
        pairwise[
            "Truth_tpm"
        ]
        .fillna(
            0.0
        )
    )

    pairwise[
        method_col
    ] = (
        pairwise[
            method_col
        ]
        .fillna(
            0.0
        )
    )

    pairwise[
        "in_truth"
    ] = (
        pairwise[
            "transcript_id"
        ]
        .isin(
            truth_set
        )
    )

    pairwise[
        "in_method"
    ] = (
        pairwise[
            "transcript_id"
        ]
        .isin(
            method_set
        )
    )

    pairwise[
        "set_membership"
    ] = np.select(
        [
            (
                pairwise[
                    "in_truth"
                ]
                &
                pairwise[
                    "in_method"
                ]
            ),
            (
                pairwise[
                    "in_truth"
                ]
                &
                ~pairwise[
                    "in_method"
                ]
            ),
            (
                ~pairwise[
                    "in_truth"
                ]
                &
                pairwise[
                    "in_method"
                ]
            ),
        ],
        [
            "overlap",
            "truth_only",
            "method_only",
        ],
        default="neither",
    )

    return (
        pairwise,
        truth_set,
        method_set,
    )


