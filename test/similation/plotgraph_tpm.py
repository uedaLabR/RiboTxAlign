def parse_gff3_attributes(text):
    result = {}

    for item in text.strip().split(";"):

        if not item:
            continue

        if "=" in item:
            key, value = item.split(
                "=",
                1,
            )

        else:
            parts = item.split(
                None,
                1,
            )

            if len(parts) != 2:
                continue

            key, value = parts

        result[
            key.strip()
        ] = (
            value.strip()
            .strip('"')
        )

    return result


def read_cds_from_gencode_gff3(path):
    """
    Build transcript-level CDS lengths from Gencode GFF3.

    CDS features can occur on multiple exons, so the CDS length for each
    transcript is the SUM of all CDS feature lengths belonging to that
    transcript.

    Transcript IDs are normalized by removing version suffixes.
    """

    cds_length = {}

    with open(path) as f:

        for line in f:

            if (
                not line.strip()
                or
                line.startswith("#")
            ):
                continue

            fields = line.rstrip().split("\t")

            if len(fields) < 9:
                continue

            if fields[2] != "CDS":
                continue

            try:
                start = int(
                    fields[3]
                )
                end = int(
                    fields[4]
                )

            except ValueError:
                continue

            length = (
                end
                -
                start
                +
                1
            )

            if length <= 0:
                continue

            attr = parse_gff3_attributes(
                fields[8]
            )

            transcript_ids = []

            # Gencode GFF3 CDS entries generally contain Parent=transcript:ENST...
            parent = attr.get(
                "Parent"
            )

            if parent:
                for value in re.split(
                    r"[,]",
                    parent,
                ):
                    tid = norm_id(
                        value
                    )

                    if (
                        tid
                        and
                        tid.startswith(
                            "ENST"
                        )
                    ):
                        transcript_ids.append(
                            tid
                        )

            # Fallback for GTF-like attributes if present.
            transcript_id = attr.get(
                "transcript_id"
            )

            if transcript_id:
                tid = norm_id(
                    transcript_id
                )

                if (
                    tid
                    and
                    tid.startswith(
                        "ENST"
                    )
                ):
                    transcript_ids.append(
                        tid
                    )

            for tid in set(
                transcript_ids
            ):
                cds_length[
                    tid
                ] = (
                    cds_length.get(
                        tid,
                        0,
                    )
                    +
                    length
                )

    df = pd.DataFrame({
        "transcript_id":
            list(
                cds_length.keys()
            ),
        "cds_length":
            list(
                cds_length.values()
            ),
    })

    print()
    print("=" * 88)
    print("GENCODE CDS LENGTHS")
    print("=" * 88)
    print(
        "Transcripts with CDS length:",
        len(df),
    )

    return df


def read_ribomap(
    stats_path,
    cds,
):
    """
    Read RiboMap transcript abundance and convert it to TPM using the
    original definition:

        rate = rabd / CDS_length
        TPM  = rate / sum(rate) * 1e6

    IMPORTANT:
      - The reported transcript set is based on rabd > 0.
      - CDS length comes from the SAME Gencode transcriptome used by
        RiboMap, not from the simulation-only CDS file.
    """

    records = []

    tid = None

    with open(stats_path) as f:

        for line in f:

            line = line.strip()

            if line.startswith("tid:"):

                tid = norm_id(
                    line.split(
                        ":",
                        1,
                    )[1]
                )

            elif (
                line.startswith("rabd:")
                and
                tid
            ):

                try:
                    value = float(
                        line.split(
                            ":",
                            1,
                        )[1]
                    )

                except ValueError:
                    continue

                records.append({
                    "transcript_id":
                        tid,

                    "rabd":
                        value,
                })

    df = (
        pd.DataFrame(
            records
        )
        .groupby(
            "transcript_id",
            as_index=False,
        )["rabd"]
        .sum()
        .merge(
            cds,
            on="transcript_id",
            how="left",
        )
    )

    positive = (
        df["rabd"] > 0
    )

    missing_all = int(
        df[
            "cds_length"
        ]
        .isna()
        .sum()
    )

    missing_positive = int(
        (
            positive
            &
            df[
                "cds_length"
            ]
            .isna()
        ).sum()
    )

    print()
    print("=" * 88)
    print("RIBOMAP LENGTH MATCHING")
    print("=" * 88)
    print(
        "RiboMap transcripts:",
        len(df),
    )
    print(
        "RiboMap rabd > 0 transcripts:",
        int(
            positive.sum()
        ),
    )
    print(
        "Without Gencode CDS length:",
        missing_all,
    )
    print(
        "rabd > 0 without Gencode CDS length:",
        missing_positive,
    )

    if missing_positive > 0:
        missing_ids = (
            df.loc[
                positive
                &
                df[
                    "cds_length"
                ]
                .isna(),
                [
                    "transcript_id",
                    "rabd",
                ],
            ]
            .copy()
        )

        missing_path = (
            PLOTS
            /
            "RiboMap_positive_without_Gencode_CDS.tsv"
        )

        missing_ids.to_csv(
            missing_path,
            sep="\t",
            index=False,
        )

        print(
            "Missing-CDS list:",
            missing_path,
        )

    # Keep the reported status independent of TPM calculation.
    df[
        "RiboMap_reported"
    ] = positive

    rate = np.where(
        (
            df[
                "cds_length"
            ].fillna(0) > 0
        ),
        (
            df[
                "rabd"
            ]
            /
            df[
                "cds_length"
            ]
        ),
        0.0,
    )

    total = rate.sum()

    df[
        "RiboMap_tpm"
    ] = (
        rate
        /
        total
        *
        1_000_000
        if total > 0
        else 0.0
    )

    return df[
        [
            "transcript_id",
            "RiboMap_tpm",
            "RiboMap_reported",
            "rabd",
            "cds_length",
        ]
    ]


